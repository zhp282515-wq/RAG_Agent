def run_side(fn, top_n: int = 5) -> list[dict]:
    rows = []
    for q in _QS:
        hits = fn(q)
        rows.append({"q": q, "hits": hits, "top": hits[:top_n]})
    return rows


def _sat(r: dict) -> int:
    # 每问:相关度 ≥ 0.60 的命中条数(与 agent 注入门槛一致)
    return sum(1 for h in r["hits"] if h["score"] >= 0.60)


def analyze(rows_vec: list[dict], rows_rer: list[dict]) -> dict:
    sv = [_sat(r) for r in rows_vec]
    sr = [_sat(r) for r in rows_rer]
    out: dict = {}
    for label, s in (("vec", sv), ("rer", sr)):
        has = sum(1 for x in s if x > 0)
        out[f"{label}_has"] = has
        out[f"{label}_has_rate"] = round(100 * has / len(s), 1)
        out[f"{label}_avg_sat"] = round(sum(s) / len(s), 2)
        out[f"{label}_sat"] = s
    # top1 归因:逐问查 _EXPECTED(人工标注),统计 hit
    attr_by_src: dict[str, dict[str, int]] = {}
    cmp = 0; hv = 0; hr = 0
    for rv, rr in zip(rows_vec, rows_rer):
        ed = _EXPECTED.get(rv["q"])
        if ed is None:
            continue
        cmp += 1
        v1 = rv["hits"][0]["file_name"] if rv["hits"] else "-"
        r1 = rr["hits"][0]["file_name"] if rr["hits"] else "-"
        hv += (v1 == ed); hr += (r1 == ed)
        b = attr_by_src.setdefault(ed, {"n": 0, "vec": 0, "rer": 0})
        b["n"] += 1; b["vec"] += (v1 == ed); b["rer"] += (r1 == ed)
    out["attr_cmp"] = cmp
    out["attr_vec_hit"] = hv
    out["attr_rer_hit"] = hr
    out["attr_by_src"] = attr_by_src
    return out


